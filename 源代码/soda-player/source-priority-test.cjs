const assert=require('node:assert/strict');
const {SourceRouter}=require('./source-router.cjs');
const music={pid:11,name:'QQ音乐',active:true,muted:false,peak:.2};
const live={pid:22,name:'YY',active:true,muted:false,peak:.2};
const page={source:'web:test',browser:'Chrome',title:'测试视频',playing:true};
const state=(audio,pages=[])=>({source:'',audio,sessions:pages,webSources:pages,foregroundName:'YY'});
const router=new SourceRouter();
assert.equal(router.choose(state([music]),1000),'audio:11');
assert.equal(router.choose(state([music],[page]),2000),'audio:11','Later browser must not override music');
assert.equal(router.choose(state([music,live],[page]),3000),'audio:11','Later live app must not override music');
assert.equal(router.choose(state([{...music,active:false},live],[page]),3100),page.source,'Music stops: browser wins over live');
assert.equal(router.choose(state([live],[{...page,playing:false}]),3200),'audio:22','Browser pauses: live becomes eligible');
const reverse=new SourceRouter();
assert.equal(reverse.choose(state([live]),1000),'audio:22');
assert.equal(reverse.choose(state([live],[page]),2000),page.source);
assert.equal(reverse.choose(state([music,live],[page]),3000),'audio:11');
assert.equal(reverse.choose({...state([music,live],[page]),selected:'web:test'},3100),null,'Manual selection stays untouched');
const native=new SourceRouter();
const browser={pid:33,name:'Chrome',active:true,muted:false,peak:.2};
assert.equal(native.choose(state([browser]),1000),'audio:33');
assert.equal(native.choose(state([browser,live]),2000),'audio:33','Browser without extension also outranks live');
console.log('PASS: category priority, both start orders, pause fallback, native browser and manual selection.');
const {excludedSource,sessionEntries}=require('./source-names.cjs');
for(const id of ['douyin','douyin.exe','抖音','C:\\Apps\\douyin.exe'])assert(excludedSource(id));
assert(!excludedSource('web:douyin'));
const entries=sessionEntries([{source:'douyin.exe'},{source:'web:douyin',label:'抖音（Chrome）'}],[{pid:99,name:'douyin',active:true}]);
assert.deepEqual(entries.map(x=>x.source),['web:douyin']);
assert.equal(new SourceRouter().choose(state([{pid:99,name:'douyin',active:true,muted:false,peak:.5}]),1000),null);
assert.equal(new SourceRouter().choose(state([],[{...page,source:'web:douyin'}]),1000),'web:douyin');
console.log('PASS: desktop Douyin excluded; browser Douyin retained.');
